"""Tables for conversion between kana and pydomino phonemes.

pydomino (https://github.com/DwangoMediaVillage/pydomino) aligns a
space-separated phoneme sequence that starts and ends with ``pau``.
Only the 39 phonemes in ``DOMINO_PHONEMES`` are accepted, and only the
phoneme transitions listed in its ``src/phoneme_transitions.txt`` are allowed.

The tables follow the labels of the current phoneme transition model:

* Consonants before "i" are not palatalized: "き" is ``k i``, not ``ky i``.
  "し", "ち" and "じ" keep ``sh``, ``ch`` and ``j``.
* A long vowel is written by repeating the vowel (``a a``); there is no
  ``a:`` phoneme.
* Devoiced vowels ``I`` and ``U`` are not produced. pydomino turns ``i`` and
  ``u`` into ``I`` and ``U`` by itself, and its alignment output contains them.
"""

